void main() {
  // For loop
  print("For Loop:");
  for (int i = 1; i <= 5; i++) {
    print(i);
  }

  // While loop
  print("While Loop:");
  int j = 1;
  while (j <= 5) {
    print(j);
    j++;
  }

  // Do-while loop
  print("Do-While Loop:");
  int k = 1;
  do {
    print(k);
    k++;
  } while (k <= 5);
}
